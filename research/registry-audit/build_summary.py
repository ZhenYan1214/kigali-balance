"""Rebuild the summary tables of the registry audit from the CSVs in this folder.

    python research/registry-audit/build_summary.py            # writes summary.md next to this file
    python research/registry-audit/build_summary.py --stdout   # prints instead

Standard library only. Every number in docs/research/03-registry-audit.md that comes
from the dataset is produced here, so the report can be checked by re-running this file.
"""
import collections
import csv
import datetime
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REGISTRIES = ('ACR', 'CAR', 'Verra')


def load(name):
    with open(os.path.join(HERE, name), encoding='utf-8') as f:
        return list(csv.DictReader(f))


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '|'.join('---' for _ in head) + '|']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def num(x):
    return f'{x:,}'


def month(d):
    return d[:7]


def months_between(a, b):
    """Inclusive list of YYYY-MM from date a to date b (b may be empty -> just a)."""
    y, m = int(a[:4]), int(a[5:7])
    y2, m2 = (int(b[:4]), int(b[5:7])) if b else (y, m)
    out = []
    while (y, m) <= (y2, m2):
        out.append(f'{y:04d}-{m:02d}')
        m += 1
        if m == 13:
            y, m = y + 1, 1
    return out


def dev_group(name):
    """Group developer names that public records tie together (see notes in the report)."""
    n = name.lower()
    if 'a-gas' in n or 'reclamation technologies' in n:
        return 'A-Gas group (incl. Reclamation Technologies / RemTec)'
    if 'tradewater' in n:
        return 'Tradewater (LLC and International SRL)'
    if n.startswith('eos climate'):
        return 'EOS Climate'
    if n.startswith('anew'):
        return 'Anew (Environmental / Carbon Development)'
    return re.sub(r'[.,]|\b(inc|llc|ltd|lp|corp|company|s\.a)\b', '', name).strip()


def main():
    P = load('projects.csv')
    I = load('issuances.csv')
    C = load('cod_identifiers.csv')
    F = load('public_fields.csv')
    out = ['# Registry audit - summary tables', '',
           f'Generated by `build_summary.py` on {datetime.date.today().isoformat()} from the CSVs in this folder '
           '(data accessed 2026-10-16). Inferences are labelled.', '']

    # ---- T1 records by registry / program / scope
    g = collections.defaultdict(lambda: [0, 0, 0])
    for p in P:
        k = (p['registry'], p['program'], p['scope'])
        g[k][0] += 1
        q = int(p['credits_issued'] or 0)
        g[k][1] += q > 0
        g[k][2] += q
    rows = [(r, pr, s, n, w, num(q)) for (r, pr, s), (n, w, q) in sorted(g.items())]
    tot = [sum(v[i] for v in g.values()) for i in range(3)]
    rows.append(('**all**', '', '', tot[0], tot[1], num(tot[2])))
    out += ['## T1. Project records collected', '',
            table(['registry', 'program', 'scope', 'projects', 'with credits', 'credits issued (registry units)'], rows), '',
            'Registry units are counted once per registry. ARB offset credits (ARBOCs) are not added on top: ARB issues them only '
            'after the registry retires the matching registry credits, so adding both would count the same tonnes twice.', '']

    # ---- T2 facility concentration (destruction only)
    dest = [p for p in P if p['scope'] == 'destruction']
    fac = collections.defaultdict(lambda: collections.Counter())
    facq = collections.defaultdict(lambda: collections.Counter())
    for p in dest:
        fac[p['facility_key']][p['registry']] += 1
        facq[p['facility_key']][p['registry']] += int(p['credits_issued'] or 0)
    rows = []
    for k in sorted(fac, key=lambda k: -sum(facq[k].values())):
        rows.append((k or '(blank)', *(fac[k][r] for r in REGISTRIES), num(sum(facq[k].values())),
                     sum(1 for r in REGISTRIES if fac[k][r])))
    top3 = sorted(fac, key=lambda k: -sum(facq[k].values()))[:3]
    share = sum(sum(facq[k].values()) for k in top3) / max(1, sum(sum(v.values()) for v in facq.values()))
    out += ['## T2. Destruction facilities behind the credited projects', '',
            table(['facility (location-derived key)', 'ACR projects', 'CAR projects', 'Verra projects', 'credits issued', 'registries'], rows), '',
            f'The three largest facilities account for {share:.1%} of registry credits issued for destruction projects in this dataset.', '']

    # ---- T3 same facility, same month, different registries / programs
    win = collections.defaultdict(set)   # (facility, month) -> {(registry, program, project)}
    prog = {p['project_id']: (p['registry'], p['program']) for p in P}
    acr_arb_periods = collections.defaultdict(list)
    for i in I:
        if i['ledger'] == 'ARB' and i['opr_id'].startswith('ACR'):
            acr_arb_periods['ACR' + i['opr_id'][3:].zfill(4)].append((i['period_start'], i['period_end']))
    for i in I:
        if i['ledger'] not in REGISTRIES or not i['period_start']:
            continue
        reg, pr = prog.get(i['project_id'], (i['ledger'], '?'))
        fk = i['facility_key']
        if not fk or fk.startswith('not') or fk.startswith('on-site'):
            continue
        end = i['period_end']
        if i['ledger'] == 'ACR' and not end:
            # ACR publishes only the vintage start; use the ARB reporting period when one starts on that date
            m = [e for s, e in acr_arb_periods.get(i['project_id'], []) if s == i['period_start']]
            end = m[0] if m else ''
        for mo in months_between(i['period_start'], end)[:12]:
            win[(fk, mo)].add((reg, pr, i['project_id']))
    by_fac = collections.defaultdict(lambda: [0, 0, set()])
    for (fk, mo), s in win.items():
        regs = {x[0] for x in s}
        progs = {(x[0], x[1]) for x in s}
        if len(regs) >= 2:
            by_fac[fk][0] += 1
            by_fac[fk][2].add(mo)
        if len(progs) >= 2:
            by_fac[fk][1] += 1
    rows = [(fk, v[0], v[1], ', '.join(sorted(v[2])[:4]) + (' ...' if len(v[2]) > 4 else '')) for fk, v in sorted(by_fac.items(), key=lambda x: -x[1][0])]
    out += ['## T3. Same facility, same month, more than one registry or programme', '',
            'A month counts when credited destruction windows at the same facility, taken from public issuance records, '
            'fall in that month for projects of at least two registries (or two programmes). ACR publishes only the vintage start date; '
            'for ACR projects without a matching ARB reporting period the window is that single month. Windows longer than 12 months are '
            'truncated to 12. This measures exposure (two ledgers drawing on one facility in one month), not double counting.', '',
            table(['facility', 'months with >=2 registries', 'months with >=2 programmes', 'first months with >=2 registries'], rows), '']

    # ---- T4 developers active in more than one registry
    dv = collections.defaultdict(lambda: collections.Counter())
    for p in P:
        dv[dev_group(p['developer'])][p['registry']] += 1
    rows = [(d, *(c[r] for r in REGISTRIES)) for d, c in sorted(dv.items(), key=lambda x: -sum(x[1].values())) if sum(1 for r in REGISTRIES if c[r]) >= 2]
    out += ['## T4. Developers with ODS/HFC projects in more than one registry', '',
            table(['developer group', 'ACR', 'CAR', 'Verra'], rows), '',
            'Grouping: "Reclamation Technologies, Inc., dba A-Gas" is how the operator is named in CAR listings (e.g. CAR1458); '
            'Tradewater LLC and Tradewater International SRL are grouped by name only (inference).', '']

    # ---- T5 ARB vs registry reconciliation
    car_iss = collections.defaultdict(int)
    acr_iss = collections.defaultdict(int)
    for i in I:
        if i['ledger'] == 'CAR':
            car_iss[(i['project_id'], i['period_start'], i['period_end'])] += int(i['quantity'])
        elif i['ledger'] == 'ACR':
            acr_iss[(i['project_id'], i['period_start'])] += int(i['quantity'])
    arb = collections.defaultdict(int)
    ea = {}
    for i in I:
        if i['ledger'] == 'ARB':
            k = (i['opr_id'], i['period_start'], i['period_end'])
            arb[k] += int(i['quantity'])
            ea[k] = i['early_action']
    res = collections.Counter()
    qsum = collections.Counter()
    for (opr, s, e), q in arb.items():
        span = ''
        if opr.startswith('CAR'):
            rq = car_iss.get((opr, s, e))
            if rq is None:
                # ARB sometimes merges consecutive registry reporting periods into one
                inside = [v for (p, a, b), v in car_iss.items() if p == opr and a >= s and b <= e]
                if inside:
                    rq, span = sum(inside), ' (ARB period spans several registry periods)'
        else:
            rq = acr_iss.get(('ACR' + opr[3:].zfill(4), s))
        tag = 'no registry record with the same period' if rq is None else ('equal' if rq == q else ('ARB < registry' if q < rq else 'ARB > registry')) + span
        key = (opr[:3], 'early action' if ea[(opr, s, e)] == 'yes' else 'compliance', tag)
        res[key] += 1
        qsum[key] += q
    rows = [(*k, v, num(qsum[k])) for k, v in sorted(res.items())]
    out += ['## T5. ARB issuance table reconciled against registry records', '',
            f'{len(arb)} distinct ARB ODS reporting periods (from {sum(1 for i in I if i["ledger"] == "ARB")} issuance rows). '
            'Matched on OPR project ID plus reporting-period dates (CAR) or period start date (ACR).', '',
            table(['registry', 'ARB type', 'result', 'periods', 'ARB credits'], rows), '']

    # ---- T6 CoD identifiers
    cod_proj = collections.defaultdict(set)
    for c in C:
        cod_proj[c['registry']].add(c['project_id'])
    car_ids = collections.Counter(c['cod_id'] for c in C if c['registry'] == 'CAR')
    reuse = [k for k, v in car_ids.items() if v > 1]
    reuse_proj = {c['project_id'] for c in C if c['registry'] == 'CAR' and c['cod_id'] in reuse}
    agas = sorted({int(c['cod_id'][5:]) for c in C if c['registry'] == 'ACR' and c['cod_id'].startswith('Plas-')})
    span = (agas[0], agas[-1]) if agas else (0, 0)
    gaps = (span[1] - span[0] + 1) - len(agas)
    vol_acr = [p for p in P if p['registry'] == 'ACR' and p['program'] == 'ACR voluntary' and p['scope'] == 'destruction']
    vol_acr_cod = [p for p in vol_acr if p['cod_ids_public'].startswith('CoD')]
    car_comp = [p for p in P if p['registry'] == 'CAR' and p['program'] != 'CAR voluntary']
    car_vol = [p for p in P if p['registry'] == 'CAR' and p['program'] == 'CAR voluntary']
    rows = [
        ('CAR voluntary protocols', len(car_vol), sum(1 for p in car_vol if p['cod_ids_public'] == 'yes'), 'structured report (ID, facility, dates, lb)'),
        ('CAR ARB / WA compliance', len(car_comp), sum(1 for p in car_comp if p['cod_ids_public'] == 'yes'), '-'),
        ('ACR voluntary destruction', len(vol_acr), len(vol_acr_cod), 'CoD PDF posted; ID sometimes in title'),
        ('ACR ARB / WA compliance', sum(1 for p in P if p['registry'] == 'ACR' and p['program'] != 'ACR voluntary' and p['scope'] == 'destruction'),
         sum(1 for p in P if p['registry'] == 'ACR' and p['program'] != 'ACR voluntary' and p['cod_ids_public'].startswith('CoD')), '-'),
        ('Verra VM0016 / AM0001', sum(1 for p in P if p['registry'] == 'Verra'), 0, 'no standalone CoD in the one document list read'),
    ]
    d_all = sum(int(p['credits_issued'] or 0) for p in dest)
    d_hidden = sum(int(p['credits_issued'] or 0) for p in dest if not (p['cod_ids_public'] == 'yes' or p['cod_ids_public'].startswith('CoD')))
    out += ['## T6. Where certificate-of-destruction identifiers are public', '',
            table(['registry / programme', 'projects', 'projects with CoD identifiers public', 'form'], rows), '',
            f'- Destruction projects whose CoD identifiers are not public in any form found here hold {num(d_hidden)} of '
            f'{num(d_all)} registry credits issued for destruction ({d_hidden / d_all:.1%}).',
            f'- CAR CoD report: {sum(1 for c in C if c["registry"] == "CAR")} rows, {len(car_ids)} distinct IDs; '
            f'{len(reuse)} IDs appear twice, all within {len(reuse_proj)} project(s) on different dates with different weights, '
            'so the published "COD Identification Number" is not unique even inside one project.',
            f'- A-Gas four-digit CoD numbers visible in ACR document titles: {len(agas)} distinct numbers between {span[0]} and {span[1]}; '
            f'{gaps} numbers in that range appear in no public record collected here (inference: they belong to destructions credited '
            'elsewhere, not credited at all, or not posted).', '']

    # ---- T7 other-programme declarations
    flags = collections.Counter()
    for p in P:
        f = p['other_program_flag']
        if 'true' in f:
            flags[(p['registry'], p['project_id'], f)] += 1
    n_acr = sum(1 for p in P if p['registry'] == 'ACR')
    n_ver = sum(1 for p in P if p['registry'] == 'Verra')
    out += ['## T7. Self-declared participation in another programme', '',
            f'- ACR `hasAnotherCarbonProgram`: true for {sum(1 for k in flags if k[0] == "ACR" and "hasAnotherCarbonProgram=true" in k[2])} of {n_acr} '
            f'ODS / reclaimed-HFC projects ({", ".join(k[1] for k in flags if k[0] == "ACR" and "hasAnotherCarbonProgram=true" in k[2])}); the other programme is not named.',
            f'- Verra `registeredOtherGhgProgram`: true for {sum(1 for k in flags if k[0] == "Verra")} of {n_ver} projects.',
            '- CAR listings have no equivalent structured field.', '']

    # ---- T8 public-field matrix
    out += ['## T8. What an outside party can see, per registry', '',
            table(['registry / programme', 'field', 'public', 'evidence'], [(f['registry_program'], f['field'], f['public'], f['evidence']) for f in F]), '']

    text = '\n'.join(out)
    if '--stdout' in sys.argv:
        sys.stdout.reconfigure(encoding='utf-8')
        print(text)
    else:
        with open(os.path.join(HERE, 'summary.md'), 'w', encoding='utf-8') as f:
            f.write(text + '\n')
        print('wrote summary.md')


if __name__ == '__main__':
    main()
